// The seeded workspace as Yjs updates: the page tree first, then one doc per page. Every doc is
// written by the plan's client id, so the same seed always gives the same bytes.
import { type PageEntry, WORKSPACE_DOC_ID, writeEntries, writePage } from '@apace/model';
import * as Y from 'yjs';
import type { SeedAsset } from './assets.ts';
import { createHasher } from './hash.ts';
import { pageContent } from './pages.ts';
import { planWorkspace, type WorkspacePlan } from './plan.ts';

export interface SeedRecord {
  readonly docId: string;
  readonly kind: 'workspace' | 'page';
  /** The doc's whole state, as one Yjs update. */
  readonly update: Uint8Array;
}

export interface SearchFixture {
  readonly query: string;
  /** The page that must be the top hit. */
  readonly expected: string;
}

/** Pages with a part to play in the bench and the tests, by id. */
export interface SeedFixtures {
  /** The page with exactly 3,000 blocks. */
  readonly largePage: string;
  /** A typical page of 35 to 45 blocks, for typing. */
  readonly typingPage: string;
  readonly pageOpenTargets: readonly string[];
  /** A page at the deepest level of the tree. */
  readonly deepPage: string;
  /** The page with the most backlinks. */
  readonly hubPage: string;
  readonly searchQueries: readonly SearchFixture[];
  readonly trash: readonly string[];
  readonly favorites: readonly string[];
}

function newDoc(plan: WorkspacePlan, docId: string): Y.Doc {
  const doc = new Y.Doc({ guid: docId });
  doc.clientID = plan.client;
  return doc;
}

function record(doc: Y.Doc, kind: SeedRecord['kind']): SeedRecord {
  const update = Y.encodeStateAsUpdate(doc);
  doc.destroy();
  return { docId: doc.guid, kind, update };
}

export function workspaceRecord(plan: WorkspacePlan): SeedRecord {
  const entries = plan.pages.map(
    (page): PageEntry => ({
      id: page.id,
      placement: {
        parent: page.parent === null ? null : (plan.pages[page.parent]?.id ?? null),
        order: page.order,
        time: page.created,
        client: plan.client,
      },
      trashed: page.trashedAt === null ? null : { at: page.trashedAt, client: plan.client },
      created: page.created,
    }),
  );
  const doc = newDoc(plan, WORKSPACE_DOC_ID);
  writeEntries(doc, entries);
  return record(doc, 'workspace');
}

/** The page at `index` as a record. It matches the same page's record from a full run. */
export function pageRecord(plan: WorkspacePlan, index: number): SeedRecord {
  const id = plan.pages[index]?.id;
  if (id === undefined) throw new Error(`There is no page ${index}`);
  const doc = newDoc(plan, id);
  writePage(doc, pageContent(plan, index));
  return record(doc, 'page');
}

/** Every record, the page tree first, then the pages in plan order. */
export function* seedRecords(plan: WorkspacePlan): Generator<SeedRecord> {
  yield workspaceRecord(plan);
  for (let index = 0; index < plan.pages.length; index++) yield pageRecord(plan, index);
}

export function seedFixtures(plan: WorkspacePlan): SeedFixtures {
  const id = (index: number | undefined) => {
    const page = index === undefined ? undefined : plan.pages[index];
    if (page === undefined) throw new Error(`There is no page ${index}`);
    return page.id;
  };
  // Each planted word is in one title only, so it, its prefix, or it with another word from
  // that title has exactly one right answer.
  const searchQueries = plan.pages.flatMap((page) => {
    if (page.planted === null) return [];
    const word = page.planted.toLowerCase();
    return [
      { query: page.planted, expected: page.id },
      { query: word.slice(0, 4), expected: page.id },
    ];
  });
  return {
    largePage: id(plan.large),
    typingPage: id(plan.typing),
    pageOpenTargets: plan.openTargets.map(id),
    deepPage: id(plan.deep),
    hubPage: id(plan.hubs[0]),
    searchQueries,
    trash: plan.pages.flatMap((page) => (page.trashedAt === null ? [] : [page.id])),
    favorites: plan.favorites.map(id),
  };
}

/** A hash of every record and asset, in order. It changes whenever any generated byte does. */
export function contentHash(records: Iterable<SeedRecord>, assets: readonly SeedAsset[]): string {
  const hasher = createHasher();
  for (const { docId, kind, update } of records) {
    hasher.updateText(`${kind}\u0000${docId}\u0000${update.length}\u0000`);
    hasher.update(update);
  }
  for (const asset of assets) {
    hasher.updateText(`asset\u0000${asset.id}\u0000${asset.bytes.length}\u0000`);
    hasher.update(asset.bytes);
  }
  return hasher.digest();
}

export interface SeededWorkspace {
  readonly plan: WorkspacePlan;
  readonly records: readonly SeedRecord[];
  readonly fixtures: SeedFixtures;
  readonly hash: string;
}

/** The whole workspace at once. The importer streams `seedRecords` instead. */
export function seedWorkspace(seed: number): SeededWorkspace {
  const plan = planWorkspace(seed);
  const records = [...seedRecords(plan)];
  return { plan, records, fixtures: seedFixtures(plan), hash: contentHash(records, plan.assets) };
}
